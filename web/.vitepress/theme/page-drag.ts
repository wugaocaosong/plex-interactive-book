import type { PageFlip } from 'page-flip'

type Direction = 'previous' | 'next'
type Point = { x: number; y: number }

/** Only the paper margins initiate a drag; content keeps its native selection/clicks. */
export function bindPageDrag(element: HTMLElement, options: {
  flip?: PageFlip
  canTurn: (direction: Direction) => boolean
  atBoundary: (direction: Direction) => boolean
  turn: (direction: Direction) => void
  onStart: () => void
  cover?: boolean
}) {
  let drag: { id: number; direction: Direction; start: Point; origin: Point; width: number;
    active: boolean; boundary: boolean; progress: number; reduced: boolean } | undefined
  let animation: Animation | undefined
  let disposed = false
  let suppressClick = false
  let clickTimer: ReturnType<typeof setTimeout> | undefined
  const point = (event: PointerEvent): Point => {
    const rect = (options.flip?.getUI().getDistElement() || element).getBoundingClientRect()
    return { x: event.clientX - rect.left, y: event.clientY - rect.top }
  }
  const resetStyle = () => {
    element.classList.remove('is-dragging')
    element.style.transform = ''
    element.style.transformOrigin = ''
    element.style.opacity = ''
  }
  function down(event: PointerEvent) {
    // Only suppress the click generated by the drag itself, never a fresh click on a control.
    if (!drag) { suppressClick = false; clearTimeout(clickTimer) }
    if (drag || animation || event.button !== 0 || !event.isPrimary ||
        (options.flip && options.flip.getState() !== 'read')) return
    const target = event.target as Element
    if (!options.cover && target.closest('a,button,input,textarea,select,[contenteditable],[data-action]')) return
    const rect = element.getBoundingClientRect()
    const x = event.clientX - rect.left
    const direction = options.cover || x > rect.width / 2 ? 'next' : 'previous'
    if (!options.cover && x > 24 && x < rect.width - 24) return
    if (!options.canTurn(direction)) return
    drag = { id: event.pointerId, direction, start: { x: event.clientX, y: event.clientY },
      origin: point(event), width: options.flip?.getBoundsRect().pageWidth || rect.width,
      active: false, boundary: options.atBoundary(direction), progress: 0,
      reduced: matchMedia('(prefers-reduced-motion: reduce)').matches }
    element.setPointerCapture(event.pointerId)
    // Preserve a normal click on the cover; paper margins themselves have no click action.
    if (!options.cover) event.preventDefault()
  }
  function move(event: PointerEvent) {
    if (!drag || event.pointerId !== drag.id) return
    const distance = (event.clientX - drag.start.x) * (drag.direction === 'next' ? -1 : 1)
    if (!drag.active) {
      if (distance < 6) return
      drag.active = true
      options.onStart()
      element.classList.add('is-dragging')
      if (!drag.boundary && !drag.reduced && options.flip) {
        // Start at the edge, before a fast pointer movement can cross the spine.
        options.flip.startUserTouch(drag.origin)
        options.flip.getFlipController().start(drag.origin)
      }
    }
    event.preventDefault()
    drag.progress = Math.max(0, Math.min(1, distance / drag.width))
    if (drag.reduced) return
    if (drag.boundary) {
      element.style.transformOrigin = drag.direction === 'next' ? 'left center' : 'right center'
      element.style.transform = `perspective(1800px) rotateY(${drag.progress * (drag.direction === 'next' ? -70 : 70)}deg)`
      element.style.opacity = String(1 - drag.progress * .2)
    } else options.flip?.userMove(point(event), true)
  }
  function finish(event?: PointerEvent, cancelled = false) {
    if (!drag || (event && event.pointerId !== drag.id)) return
    const ended = drag
    drag = undefined
    if (element.hasPointerCapture(ended.id)) element.releasePointerCapture(ended.id)
    if (!ended.active) return
    suppressClick = true
    clearTimeout(clickTimer)
    clickTimer = setTimeout(() => { suppressClick = false }, 350)
    const complete = !cancelled && ended.progress >= (options.flip?.getOrientation() === 'landscape' ? 1 : .5)
    if (!ended.boundary && !ended.reduced && options.flip) {
      // Returning the fold to its starting edge guarantees cancellation on blur/resize/Escape.
      if (cancelled) options.flip.getFlipController().fold(ended.origin)
      options.flip.userStop(ended.origin)
      resetStyle()
      return
    }
    const done = () => { animation = undefined; resetStyle(); if (complete && !disposed) options.turn(ended.direction) }
    if (ended.reduced) { done(); return }
    animation = element.animate([
      { transform: element.style.transform, opacity: element.style.opacity || '1' },
      { transform: complete ? `perspective(1800px) rotateY(${ended.direction === 'next' ? -90 : 90}deg)` : 'perspective(1800px) rotateY(0deg)', opacity: complete ? .2 : 1 }
    ], { duration: 220, easing: 'ease-out' })
    animation.onfinish = done
  }
  function click(event: MouseEvent) { if (suppressClick) { suppressClick = false; clearTimeout(clickTimer); event.preventDefault(); event.stopImmediatePropagation() } }
  const cancel = () => finish(undefined, true)
  const up = (event: PointerEvent) => finish(event)
  const pointerCancel = (event: PointerEvent) => finish(event, true)
  const key = (event: KeyboardEvent) => { if (event.key === 'Escape') cancel() }
  element.addEventListener('pointerdown', down)
  element.addEventListener('pointermove', move)
  element.addEventListener('pointerup', up)
  element.addEventListener('pointercancel', pointerCancel)
  element.addEventListener('lostpointercapture', pointerCancel)
  element.addEventListener('click', click, true)
  window.addEventListener('blur', cancel)
  window.addEventListener('resize', cancel)
  window.addEventListener('keydown', key)
  return () => {
    disposed = true
    cancel()
    animation?.cancel()
    clearTimeout(clickTimer)
    resetStyle()
    element.removeEventListener('pointerdown', down)
    element.removeEventListener('pointermove', move)
    element.removeEventListener('pointerup', up)
    element.removeEventListener('pointercancel', pointerCancel)
    element.removeEventListener('lostpointercapture', pointerCancel)
    element.removeEventListener('click', click, true)
    window.removeEventListener('blur', cancel)
    window.removeEventListener('resize', cancel)
    window.removeEventListener('keydown', key)
  }
}
