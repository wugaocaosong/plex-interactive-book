test('every bundled Python example referenced by the book runs with its own driver',async({page})=>{
  test.setTimeout(300000)
  const manifest=JSON.parse(readFileSync('web/public/book/manifest.json','utf8'))
  const examples=new Map<string,string>()
  for(const section of manifest.pages){const data=JSON.parse(readFileSync(`web/public/book/pages/${section.id}.json`,'utf8'));for(const ref of data.codeExamples){const py=ref.variants.find((v:any)=>v.language==='python');if(py)examples.set(py.sourcePath.replace('codes/python/',''),py.fullSource)}}
  await page.goto('/')
  const results=await page.evaluate(async entries=>{
    const worker=new Worker('/python-worker.js',{type:'module'})
    const send=(message:any,seconds:number)=>new Promise<{type:string,text?:string}>(resolve=>{const timer=setTimeout(()=>resolve({type:'error',text:'timeout'}),seconds*1000);worker.onmessage=e=>{if(['ready','done','error'].includes(e.data.type)){clearTimeout(timer);resolve(e.data)}};worker.postMessage(message)})
    const initialized=await send({type:'init'},90);if(initialized.type==='error')throw Error(initialized.text)
    const results=[];for(const [path,code] of entries){const result=await send({type:'run',path,code},10);results.push({path,...result});if(result.text==='timeout')break}worker.terminate();return results
  },[...examples])
  expect(results.filter(r=>r.type!=='done')).toEqual([])
  expect(results.length).toBe(examples.size)
  console.log(`Executed ${results.length} complete upstream Python examples`)
})
