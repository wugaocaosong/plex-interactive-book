import { test, expect } from '@playwright/test';

test('QA drafts, publish, replies, likes, resolution, search and saved records', async ({ page }) => {
  await page.goto('/read/unit/lab/dispatch');
  await page.getByRole('button', {name:'留言', exact:true}).click();
  const board = page.locator('.qa-board');
  await expect(board.getByRole('button', {name:'发布', exact:true})).toBeDisabled();
  await board.getByLabel('你的昵称').fill('QA测试');
  const text = board.getByLabel('留言内容', {exact:true});
  await text.fill('这里是草稿');
  await text.press('Enter');
  await expect(text).toHaveValue('这里是草稿\n');
  await page.getByRole('button', {name:'关闭', exact:true}).click();
  await page.getByRole('button', {name:'留言', exact:true}).click();
  await expect(text).toHaveValue('这里是草稿\n');
  await text.fill('QA回归测试：调度算法如何选择？');
  await board.getByRole('button', {name:'发布', exact:true}).click();
  const item = board.locator('.qa-item').filter({hasText:'QA回归测试：调度算法如何选择？'});
  await expect(item).toContainText('待解答');
  await expect(board.getByRole('status')).toContainText('已发布');
  await item.locator('.qa-like').click();
  await expect(item.locator('.qa-like')).toHaveAttribute('aria-pressed', 'true');
  await item.getByRole('button', {name:'回复', exact:true}).click();
  await board.getByLabel('回复内容').fill('先比较任务优先级，再考虑路径成本。');
  await item.locator('.qa-reply-box').getByRole('button', {name:'回复', exact:true}).click();
  await expect(item.locator('.qa-replies')).toContainText('先比较任务优先级');
  await item.getByRole('button', {name:'标记已解决', exact:true}).click();
  await expect(item.locator('.qa-state')).toHaveText('已解决');
  await board.getByLabel('提问状态', {exact:true}).selectOption('open');
  await expect(item).toHaveCount(0);
  await board.getByLabel('提问状态', {exact:true}).selectOption('resolved');
  await expect(item).toHaveCount(1);
  await board.getByLabel('在留言中搜索').fill('不存在的搜索词');
  await expect(board.locator('.qa-empty')).toContainText('没有匹配');
  await board.getByLabel('在留言中搜索').fill('');
  await page.reload();
  await page.getByRole('button', {name:'留言', exact:true}).click();
  await expect(item).toContainText('已解决');
  await expect(item.locator('.qa-replies')).toContainText('先比较任务优先级');
  await expect(board.locator('.qa-foot-note')).toContainText('不会自动同步给其他读者');
});
